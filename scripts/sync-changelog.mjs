// Regenerates docs-site/changelog.mdx from the repository CHANGELOG.md that
// Changesets maintains. Run via `npm run changelog:sync` (also part of
// `npm run changeset:version`). If there is no CHANGELOG.md yet, it leaves the
// existing page untouched.
import { existsSync, readFileSync, writeFileSync } from "node:fs"

const CHANGELOG = "CHANGELOG.md"
const PAGE = "docs-site/changelog.mdx"

if (!existsSync(CHANGELOG)) {
  console.log(`No ${CHANGELOG} yet; leaving ${PAGE} as-is.`)
  process.exit(0)
}

const text = readFileSync(CHANGELOG, "utf8")
const lines = text.split(/\r?\n/)

// Split into "## <version>" sections, ignoring the leading "# <pkg>" title.
const sections = []
let current = null
for (const line of lines) {
  const version = /^##\s+(.+?)\s*$/.exec(line)
  if (version) {
    current = { version: version[1], body: [] }
    sections.push(current)
    continue
  }
  if (current) current.body.push(line)
}

if (sections.length === 0) {
  console.log(`No version sections found in ${CHANGELOG}; leaving ${PAGE} as-is.`)
  process.exit(0)
}

const fence = (body) =>
  body
    .map((line) => line.replace(/[ \t]+$/, ""))
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()

const updates = sections.map(({ version, body }) => {
  const content = fence(body)
  return content
    ? `<Update label="${version}">\n${content}\n</Update>`
    : `<Update label="${version}" />`
})

const page = `---
title: What's New
description: Release notes for Celly. New entries are generated from CHANGELOG.md.
---

{/* Generated by scripts/sync-changelog.mjs — do not edit by hand. */}

${updates.join("\n\n")}
`

writeFileSync(PAGE, page)
console.log(`Wrote ${PAGE} from ${CHANGELOG} (${sections.length} release(s)).`)
